// GetPageInfo 返回当前请求的分页信息（页码和每页大小）。
// 默认每页大小为20，通过调用 GetPageInfoByParam 方法从请求参数中获取分页信息。
// 返回：
//   - page: 当前页码
//   - pageSize: 每页大小
func (c *BaseController) GetPageInfo() (page, pageSize int) {
	return c.GetPageInfoByParam("page", "limit", 20)
}

// GetPageInfoDefault 根据默认分页大小获取当前页码和每页大小。
// 如果传入的默认分页大小 pageSizeDefault 小于等于 0，则使用默认值 20。
// 返回的 page 和 pageSize 是通过调用 GetPageInfoByParam 方法从请求参数中解析得到的。
// 参数:
//
//	pageSizeDefault: 默认的每页大小。
//
// 返回值:
//
//	page: 当前页码。
//	pageSize: 每页大小。
func (c *BaseController) GetPageInfoDefault(pageSizeDefault int) (page, pageSize int) {
	if pageSizeDefault <= 0 {
		pageSizeDefault = 20
	}
	return c.GetPageInfoByParam("page", "limit", pageSizeDefault)
}

// GetPageInfoByParam 根据请求参数获取分页信息。
//
// 参数:
//   - pageParam: 请求中表示页码的参数名，如果为空则默认为 "page"。
//   - pageSizeParam: 请求中表示每页大小的参数名，如果为空则默认为 "limit"。
//   - pageSizeDefault: 每页大小的默认值（未提供参数时使用）。
//
// 返回值:
//   - page: 解析后的页码，默认为 1。
//   - pageSize: 解析后的每页大小，默认为 20。
//
// 说明:
//   - 该方法用于从请求参数中提取分页信息，适用于需要分页查询的场景。
//   - 如果参数未提供，则使用默认值。
func (c *BaseController) GetPageInfoByParam(pageParam, pageSizeParam string, pageSizeDefault int) (page, pageSize int) {
	if pageParam == "" {
		pageParam = "page"
	}
	if pageSizeParam == "" {
		pageSizeParam = "limit"
	}
	page = c.GetInt(pageParam, 1)
	pageSize = c.GetInt(pageSizeParam, 20)
	return
}
